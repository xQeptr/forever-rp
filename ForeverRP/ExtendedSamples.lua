function A:GetSamplePack(category,language,channel)
  local lang=language=='de' and 'de' or 'en'
  local mode=channel=='say' and 'say' or 'me'
  if category=='alcohol' then category='drink' end
  local base=previous(self,category,lang,mode)
  if lang~='en' then return base end -- legacy DE content kept dormant
  local categoryExtra=more[category] or more.other
  local additional=categoryExtra[mode]
  local unique={}
  for _,line in ipairs(base) do unique[line]=true end
  for _,line in ipairs(additional) do
    if not unique[line] then base[#base+1]=line; unique[line]=true end
  end
  return base
end
