function A:GetSamplePack(category,language,channel)
  local lang=language=='de' and 'de' or 'en'
  local kind=channel=='say' and 'say' or 'me'
  if lang=='en' and kind=='me' then return oldGetPack(self,category) end
  local pack=(packs[category] or packs.other)[lang..'_'..kind] or {}
